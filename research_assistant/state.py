from typing import TypedDict


class ResearchState(TypedDict):
    """The central state dictionary for our LangGraph research workflow.

    Think of State as the shared memory of the graph.
    - Each node receives this dictionary as its input.
    - Each node does some work and returns a dictionary with the fields it wants to update.
    - LangGraph automatically merges the node's returned dictionary into this state.
    """
    question: str               # The user's research question (input to node 1)
    search_queries: list[str]   # 2-3 search queries generated by node 1 (input to node 2)
    search_results: list[dict]  # Web search results collected by node 2 (input to node 3)
    final_report: str           # The final summarized report generated by node 3

