import json
import logging
import re
from typing import Any

import config
from research_assistant.state import ResearchState

logger = logging.getLogger(__name__)


def plan_queries(state: ResearchState) -> dict[str, Any]:
    """Node 1: Plan Search Queries.

    Purpose:
    Decomposes the user's research question into 2-3 focused web search queries.

    LangGraph Concept:
    A 'Node' is simply a Python function that takes the current State as an argument
    and returns a dictionary containing the fields it wants to add or update in the State.
    Here, it takes state['question'] and returns {'search_queries': [...]}.
    """
    question = state.get("question", "").strip()
    if not question:
        return {"search_queries": []}

    # If an OpenAI API key is available, use the LLM to generate queries
    if config.OPENAI_API_KEY:
        try:
            from openai import OpenAI
            client = OpenAI(api_key=config.OPENAI_API_KEY)
            
            prompt = (
                f"You are a research planning assistant. Given this research question:\n"
                f"\"{question}\"\n\n"
                f"Generate exactly 2 or 3 concise, highly effective search queries to find accurate information.\n"
                f"Return ONLY a JSON list of strings, for example: [\"query 1\", \"query 2\"]"
            )
            response = client.chat.completions.create(
                model=config.LLM_MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.2,
            )
            content = response.choices[0].message.content or ""
            
            # Clean up JSON formatting if surrounded by markdown code fences
            cleaned = content.strip()
            match = re.search(r"```(?:json)?\s*(.*?)\s*```", cleaned, re.DOTALL)
            if match:
                cleaned = match.group(1).strip()
                
            queries = json.loads(cleaned)
            if isinstance(queries, list) and queries:
                valid_queries = [str(q).strip() for q in queries if str(q).strip()]
                return {"search_queries": valid_queries[:3]}
        except Exception as e:
            logger.warning(f"LLM query planning failed: {e}. Falling back to default queries.")

    # Deterministic fallback when no API key is provided or if the LLM call fails
    return {
        "search_queries": [
            f"{question}",
            f"{question} key concepts and applications",
            f"{question} best practices and examples",
        ]
    }


def search_web(state: ResearchState) -> dict[str, Any]:
    """Node 2: Search the Web.

    Purpose:
    Executes web searches for the queries generated by Node 1 using Tavily,
    extracts the title, url, and content for each result, and removes duplicate URLs.

    LangGraph Concept:
    This node reads 'search_queries' from the state, runs I/O (web searches),
    and returns {'search_results': [...]}.
    """
    queries = state.get("search_queries", [])
    if not queries:
        return {"search_results": []}

    results: list[dict] = []
    seen_urls: set[str] = set()

    # If Tavily API key is provided, perform live web search
    if config.TAVILY_API_KEY:
        try:
            from tavily import TavilyClient
            client = TavilyClient(api_key=config.TAVILY_API_KEY)

            for query in queries:
                try:
                    response = client.search(query=query, max_results=3)
                    for item in response.get("results", []):
                        url = (item.get("url") or "").strip()
                        # Deduplicate by URL
                        if url and url not in seen_urls:
                            seen_urls.add(url)
                            results.append({
                                "title": item.get("title", "Untitled Source"),
                                "url": url,
                                "content": item.get("content", "").strip(),
                                "query": query,
                            })
                except Exception as query_err:
                    logger.warning(f"Search failed for query '{query}': {query_err}")
            return {"search_results": results}
        except Exception as e:
            logger.warning(f"Tavily client error: {e}. Using fallback search results.")

    # Fallback mock search results for offline development and testing
    for query in queries:
        mock_url = f"https://example.com/{query.replace(' ', '-').lower()}"
        if mock_url not in seen_urls:
            seen_urls.add(mock_url)
            results.append({
                "title": f"Guide to {query.title()}",
                "url": mock_url,
                "content": f"Relevant factual overview and evidence regarding {query}.",
                "query": query,
            })

    return {"search_results": results}


def generate_report(state: ResearchState) -> dict[str, Any]:
    """Node 3: Generate the Final Report.

    Purpose:
    Synthesizes the search results gathered by Node 2 into a clear, structured research report:
    1. Summary
    2. Key Findings
    3. Sources
    4. Limitations or missing evidence

    LangGraph Concept:
    This is the final node before END. It reads 'question' and 'search_results'
    and returns {'final_report': report_text}.
    """
    question = state.get("question", "")
    search_results = state.get("search_results", [])

    # Handle empty search results gracefully
    if not search_results:
        no_evidence_report = (
            f"# Research Report: {question}\n\n"
            "## Summary\n"
            "The research could not be completed reliably because no relevant search results were found.\n\n"
            "## Limitations\n"
            "No evidence was retrieved. Please check your query or verify your search API credentials."
        )
        return {"final_report": no_evidence_report}

    # Format retrieved evidence as context for the LLM
    context_blocks = []
    for idx, res in enumerate(search_results, start=1):
        context_blocks.append(
            f"Source [{idx}]: {res.get('title')}\n"
            f"URL: {res.get('url')}\n"
            f"Content: {res.get('content')}"
        )
    evidence_text = "\n\n".join(context_blocks)

    # Use LLM to synthesize if OpenAI API key is set
    if config.OPENAI_API_KEY:
        try:
            from openai import OpenAI
            client = OpenAI(api_key=config.OPENAI_API_KEY)

            system_prompt = (
                "You are an objective AI research assistant. Your job is to create a concise research report "
                "based ONLY on the provided web search evidence.\n\n"
                "Report Structure:\n"
                "1. Summary\n"
                "2. Key Findings (3-5 bullet points)\n"
                "3. Source Links (bulleted list of URLs)\n"
                "4. Limitations (any gaps or missing evidence)\n\n"
                "Do NOT fabricate sources or information not present in the evidence."
            )
            user_prompt = (
                f"Research Question: {question}\n\n"
                f"Retrieved Evidence:\n{evidence_text}"
            )
            response = client.chat.completions.create(
                model=config.LLM_MODEL,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.2,
            )
            report = response.choices[0].message.content or ""
            if report.strip():
                return {"final_report": report.strip()}
        except Exception as e:
            logger.warning(f"LLM report generation failed: {e}. Using structured fallback report.")

    # Deterministic fallback report directly grounded in the collected evidence
    summary = f"Synthesized research report answering: '{question}' based on {len(search_results)} gathered source(s)."
    
    findings = []
    sources = []
    for idx, item in enumerate(search_results, start=1):
        findings.append(f"- **Finding {idx}**: {item.get('content', 'Evidence collected from web search.')} (Source: {item.get('title')})")
        sources.append(f"- [{item.get('title')}]({item.get('url')})")

    report_lines = [
        f"# Research Report: {question}",
        "",
        "## 1. Summary",
        summary,
        "",
        "## 2. Key Findings",
        "\n".join(findings[:5]),
        "",
        "## 3. Source Links",
        "\n".join(sources),
        "",
        "## 4. Limitations",
        "- Findings are based strictly on initial web search results.",
        "- Additional in-depth domain verification is recommended for production decisions.",
    ]

    return {"final_report": "\n".join(report_lines)}
